#!/usr/bin/env python
"""Regenerate every PubChem retrieval result currently on disk into complete
CSV + LaTeX tables, across all evaluation tracks (global, RI-window ladder, MW-
window, RI-union-MW, heavy-atom ladder) and all three models with PubChem-scale
predictions (ICICLE, NEIMS, MassFormer). RASSP has no PubChem-scale batch-
inference run, so it is not included here.

The MW->RI and heavy-atom->RI "funnel" tracks (rank by RI within an MW/HA-filtered
subset) were confirmed a null result (funnel never beat RI-only ranking, at any
scale, for any model) and are not reported here -- the underlying
evaluate_mw_then_ri/evaluate_heavy_atom_then_ri functions and their config flags
have been removed from pubchem_global_retrieval.py.

Uses autofail top-1/top-10 accuracy throughout, never inject — a query
whose true molecule falls outside its own candidate window automatically
fails at the real retrieval task, so inject (which silently ignores those
cases) is never the right metric for windowed retrieval comparisons.

Run: uv run examples/scripts/evaluation/dump_complete_retrieval_tables.py
Outputs: figures/retrieval_pubchem_tables/*.csv and *.tex
"""

import json
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[3]
RESULTS = REPO_ROOT / "results"
OUT_DIR = REPO_ROOT / "figures" / "retrieval_pubchem_tables"
OUT_DIR.mkdir(parents=True, exist_ok=True)

MODEL_DIRS = {
    "ICICLE": RESULTS / "pubchem_retrieval_eval_icicle_rerun_260710",
    "NEIMS": RESULTS / "pubchem_retrieval_eval_neims",
    "MassFormer": RESULTS / "pubchem_retrieval_eval_massformer",
}

RI_TYPES = ["StdNP", "SemiStdNP", "StdPolar"]
RI_LEVELS = ["1000", "100000", "1000000", "10000000", "all"]
LEVEL_LABELS = {
    "1000": "1k",
    "100000": "100k",
    "1000000": "1M",
    "10000000": "10M",
    "all": "all",
}
MW_TAGS = ["80", "10_80", "10_10", "5"]
MW_LABELS = {
    "80": r"$\pm$80Da",
    "10_80": "[-10,+80]Da",
    "10_10": "[-10,+10]Da",
    "5": r"$\pm$5Da",
}
HA_WINDOWS = [1, 2, 3, 6, 8]


def safe_load(path: Path):
    if not path.exists():
        return None
    with open(path) as f:
        return json.load(f)


def top1(entry: dict | None) -> float | None:
    """Autofail top-1 accuracy from a {"cosine": {...}} leaf, or None."""
    if entry is None:
        return None
    try:
        return entry["autofail"]["cosine"]["top_1_accuracy"]
    except (KeyError, TypeError):
        return None


def top10(entry: dict | None) -> float | None:
    if entry is None:
        return None
    try:
        return entry["autofail"]["cosine"]["top_10_accuracy"]
    except (KeyError, TypeError):
        return None


def fmt_pct(v: float | None) -> str:
    return "--" if v is None or pd.isna(v) else f"{v * 100:.2f}"


def df_to_latex(
    df: pd.DataFrame, caption: str, label: str, col_spec: str | None = None
) -> str:
    """Booktabs-style standalone table, matching
    figures/table_qcxms_comparison.tex."""
    header_overrides = {
        "ri_type": "RI type",
        "ri_window": "RI window",
        "mw_window": "MW window",
        "ha_window": "HA window",
        "model": "Model",
    }
    display_cols = [c for c in df.columns if c not in ("top1", "top10")]
    headers = [
        header_overrides.get(c, c.replace("_", " ").title())
        for c in display_cols
    ] + [
        "Top-1 (\\%)",
        "Top-10 (\\%)",
    ]
    col_spec = col_spec or ("l" * len(display_cols) + "cc")

    lines = [
        r"\begin{table}[H]",
        r"\centering",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        rf"\begin{{tabular}}{{{col_spec}}}",
        r"\toprule",
        " & ".join(headers) + r" \\",
        r"\midrule",
    ]
    for _, row in df.iterrows():
        cells = [str(row[c]) for c in display_cols] + [
            fmt_pct(row["top1"]),
            fmt_pct(row["top10"]),
        ]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines)


def write_table(
    name: str,
    df: pd.DataFrame,
    caption: str,
    label: str,
    col_spec: str | None = None,
) -> None:
    df.to_csv(OUT_DIR / f"{name}.csv", index=False)
    tex = df_to_latex(df, caption, label, col_spec)
    header = (
        f"% Standalone table, regenerated by\n"
        f"% examples/scripts/evaluation/dump_complete_retrieval_tables.py\n"
        f"% Do not hand-edit -- rerun the script instead.\n\n"
    )
    (OUT_DIR / f"{name}.tex").write_text(header + tex + "\n")
    print(f"=== {name} ({len(df)} rows) ===")
    print(df.to_string(index=False))
    print()


all_tables = {}

# ---------------------------------------------------------------------------
# 1. Global retrieval (no filter) -- single row per model
# ---------------------------------------------------------------------------
rows = []
for model, d in MODEL_DIRS.items():
    data = safe_load(d / "retrieval_global_results.json")
    entry = data["all"] if data else None
    rows.append({"model": model, "top1": top1(entry), "top10": top10(entry)})
all_tables["1_global_retrieval"] = (
    pd.DataFrame(rows),
    "Global PubChem retrieval (no candidate filter), autofail top-1/top-10 accuracy. "
    "True global rank against the full $\\sim$93.6M-row PubChem candidate pool.",
    "tab:pubchem-retrieval-global",
)

# ---------------------------------------------------------------------------
# 2. RI-window ladder -- all 3 RI types, all 3 models
# ---------------------------------------------------------------------------
rows = []
for model, d in MODEL_DIRS.items():
    for ri_type in RI_TYPES:
        data = safe_load(d / f"retrieval_ablation_{ri_type}.json")
        for level in RI_LEVELS:
            entry = data.get(level) if data else None
            rows.append(
                {
                    "model": model,
                    "ri_type": ri_type,
                    "ri_window": LEVEL_LABELS[level],
                    "top1": top1(entry),
                    "top10": top10(entry),
                }
            )
all_tables["2_ri_window_ladder"] = (
    pd.DataFrame(rows),
    "RI-window retrieval ladder: candidates restricted to the $N$ nearest by predicted "
    "retention index, autofail top-1/top-10 accuracy. All three RI types "
    "(StdNP, SemiStdNP, StdPolar), all 5 window sizes.",
    "tab:pubchem-retrieval-ri-ladder",
    "llcc",
)

# ---------------------------------------------------------------------------
# 3. MW-window (global, no RI restriction) -- all 4 widths, all 3 models
# ---------------------------------------------------------------------------
rows = []
for model, d in MODEL_DIRS.items():
    for tag in MW_TAGS:
        data = safe_load(d / f"retrieval_mw{tag}_global_results.json")
        entry = data["all"] if data else None
        rows.append(
            {
                "model": model,
                "mw_window": MW_LABELS[tag],
                "top1": top1(entry),
                "top10": top10(entry),
            }
        )
all_tables["3_mw_window_global"] = (
    pd.DataFrame(rows),
    "MW-window retrieval, global (no RI restriction): candidates restricted to a "
    "Da window around the query's own highest observed predicted peak, scored "
    "against the full test set.",
    "tab:pubchem-retrieval-mw-global",
)

# ---------------------------------------------------------------------------
# 4. MW-window restricted to RI-having queries (StdNP only)
# ---------------------------------------------------------------------------
rows = []
for model, d in MODEL_DIRS.items():
    for tag in MW_TAGS:
        data = safe_load(d / f"retrieval_mw{tag}_results.json")
        entry = data.get("StdNP") if data else None
        rows.append(
            {
                "model": model,
                "mw_window": MW_LABELS[tag],
                "top1": top1(entry),
                "top10": top10(entry),
            }
        )
all_tables["4_mw_window_stdnp_restricted"] = (
    pd.DataFrame(rows),
    "MW-window retrieval, restricted to StdNP-having queries (the base query set "
    "used by the funnel/union tracks below). Never run for SemiStdNP/StdPolar.",
    "tab:pubchem-retrieval-mw-stdnp",
)

# ---------------------------------------------------------------------------
# 6. RI union MW (StdNP only)
# ---------------------------------------------------------------------------
rows = []
for model, d in MODEL_DIRS.items():
    for tag in MW_TAGS:
        data = safe_load(d / f"retrieval_union_mw{tag}_results.json")
        stdnp = data.get("StdNP") if data else None
        for level in RI_LEVELS[:-1]:
            entry = stdnp.get(level) if stdnp else None
            rows.append(
                {
                    "model": model,
                    "mw_window": MW_LABELS[tag],
                    "ri_window": LEVEL_LABELS[level],
                    "top1": top1(entry),
                    "top10": top10(entry),
                }
            )
all_tables["6_ri_union_mw"] = (
    pd.DataFrame(rows),
    "RI$\\cup$MW union (StdNP only): union of the RI-window and MW-window candidate "
    "pools -- a query only fails if excluded from both filters simultaneously. "
    "Never run for SemiStdNP/StdPolar.",
    "tab:pubchem-retrieval-ri-mw-union",
    "llcc",
)

# ---------------------------------------------------------------------------
# 7. Heavy-atom window (global, no RI restriction) -- ICICLE only
#    (NEIMS/MassFormer heavy-atom runs all crashed / never completed)
# ---------------------------------------------------------------------------
rows = []
for model, d in MODEL_DIRS.items():
    for w in HA_WINDOWS:
        data = safe_load(d / f"retrieval_heavy_atom{w}_global_results.json")
        entry = data["all"] if data else None
        rows.append(
            {
                "model": model,
                "ha_window": f"$\\pm${w}",
                "top1": top1(entry),
                "top10": top10(entry),
            }
        )
all_tables["7_heavy_atom_global"] = (
    pd.DataFrame(rows),
    "Heavy-atom-window retrieval, global (no RI restriction): candidates restricted "
    "to $\\pm N$ heavy atoms of the query's own predicted heavy-atom count. "
    "ICICLE only -- every NEIMS/MassFormer attempt crashed (CUDA OOM) or was cut "
    "off mid-scan without producing a result file.",
    "tab:pubchem-retrieval-ha-global",
)

# ---------------------------------------------------------------------------
# 8. Heavy-atom restricted to RI-having queries (StdNP only) -- ICICLE only
# ---------------------------------------------------------------------------
rows = []
for model, d in MODEL_DIRS.items():
    for w in HA_WINDOWS:
        data = safe_load(d / f"retrieval_heavy_atom{w}_results.json")
        entry = data.get("StdNP") if data else None
        rows.append(
            {
                "model": model,
                "ha_window": f"$\\pm${w}",
                "top1": top1(entry),
                "top10": top10(entry),
            }
        )
all_tables["8_heavy_atom_stdnp_restricted"] = (
    pd.DataFrame(rows),
    "Heavy-atom-window retrieval, restricted to StdNP-having queries. ICICLE only, "
    "same reason as Table~\\ref{tab:pubchem-retrieval-ha-global}.",
    "tab:pubchem-retrieval-ha-stdnp",
)

for name, (df, caption, label, *rest) in all_tables.items():
    col_spec = rest[0] if rest else None
    write_table(name, df, caption, label, col_spec)

print(f"All CSVs + .tex files written to {OUT_DIR}")
