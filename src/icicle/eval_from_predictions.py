#!/usr/bin/env python
"""Evaluate pre-computed predictions from any baseline model.

This script loads predictions from an HDF5 file (generated by baseline inference scripts)
and computes similarity and retrieval metrics using ICICLE's metrics.

This enables unified evaluation across different models that may run in different
conda environments (e.g., MassFormer, RASSP).

Usage:
    # Similarity evaluation
    uv run src/icicle/eval_from_predictions.py \
        --predictions results/predictions/massformer_nist23.hdf5 \
        --ground-truth data/NIST2023_GCMS_main/spectra.hdf5 \
        --labels data/NIST2023_GCMS_main/metadata.tsv \
        --splits data/NIST2023_GCMS_main/splits/scaffold.tsv \
        --output results/eval/massformer \
        --mode similarity

    # Full evaluation (similarity + retrieval)
    uv run src/icicle/eval_from_predictions.py \
        --predictions results/predictions/massformer_nist23.hdf5 \
        --ground-truth data/NIST2023_GCMS_main/spectra.hdf5 \
        --labels data/NIST2023_GCMS_main/metadata.tsv \
        --splits data/NIST2023_GCMS_main/splits/scaffold.tsv \
        --output results/eval/massformer \
        --mode all

    # Retrieval against full PubChem isomers (recommended for external baselines)
    uv run src/icicle/eval_from_predictions.py \
        --predictions /home/magled/icicle-dev/baselines/massformer/results/predictions/massformer_nist23_scaffold.hdf5 \
        --ground-truth data/NIST2023_GCMS_main/spectra.hdf5 \
        --labels data/NIST2023_GCMS_main/metadata.tsv \
        --splits data/NIST2023_GCMS_main/splits/scaffold_no_xeno_aas_deduplicated.tsv \
        --output results/eval/massformer_scaffold_new_retrieval \
        --mode all \
        --candidates-pickle data/NIST2023_GCMS_main/retrieval/cands_pickled_scaffold_50.pkl \
        --formula-map data/NIST2023_GCMS_main/retrieval/pubchem_formula_map_subset.p

Expected HDF5 predictions format:
    /<mol_id>/
        attrs:
            - smiles: str
            - inchi_key: str
        datasets:
            - predicted_intensities: float32[num_bins]
            - mz_bins: float32[num_bins]
"""

import argparse
import logging
import pickle
import re
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import h5py
import numpy as np
import pandas as pd
from tqdm import tqdm

from icicle.utils.eval.data_loading import retrieve_ground_truth
from icicle.utils.eval.metrics_computation import (
    compute_metrics_for_spectra,
    get_similarity_column_names,
)

logging.basicConfig(
    level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s"
)


def load_ground_truth_from_mgf(
    mgf_path: str,
    labels_path: str,
    mol_ids: List[str],
    min_mz: float,
    max_mz: float,
    bin_width: float,
) -> Dict:
    """Load and bin ground truth spectra from a SIRIUS-style MGF file.

    Matches entries by LIBRARY_ID (= spec column in labels.tsv). Returns a dict
    mapping standardized_smiles -> {mol_id, inchi_key, intensities, mz_bins}.
    """
    from icicle.data.transforms.spectrum import SpecBinner

    labels_df = pd.read_csv(labels_path, sep="\t")
    mol_id_col = "spec" if "spec" in labels_df.columns else "mol_id"
    smiles_col = (
        "smiles" if "smiles" in labels_df.columns else "standardized_smiles"
    )
    ik_col = "inchikey" if "inchikey" in labels_df.columns else "inchi_key"

    id_to_row = {str(row[mol_id_col]): row for _, row in labels_df.iterrows()}
    mol_ids_set = set(str(m) for m in mol_ids)

    binner = SpecBinner(min_mz=min_mz, max_mz=max_mz, bin_width=bin_width)
    num_bins = int((max_mz - min_mz) / bin_width)
    mz_values = np.linspace(min_mz, max_mz, num_bins, endpoint=False).astype(
        np.float32
    )

    ground_truth_map = {}
    current_id = None
    masses_buf: List[float] = []
    intensities_buf: List[float] = []

    def _flush(lib_id, masses, intensities):
        if lib_id not in mol_ids_set or lib_id not in id_to_row:
            return
        row = id_to_row[lib_id]
        smiles = row[smiles_col]
        inchi_key = row[ik_col]
        raw_mz = np.array(masses, dtype=np.float32)
        raw_int = np.array(intensities, dtype=np.float32)
        binned = binner(raw_mz, raw_int)
        binned_int = binned["spectrum"].numpy()
        max_val = binned_int.max()
        if max_val > 0:
            binned_int = binned_int / max_val
        ground_truth_map[smiles] = {
            "mol_id": lib_id,
            "inchi_key": inchi_key,
            "standardized_smiles": smiles,
            "mz_bins": mz_values,
            "intensities": binned_int,
        }

    with open(mgf_path) as fh:
        for line in fh:
            line = line.rstrip()
            if line == "BEGIN IONS":
                current_id = None
                masses_buf = []
                intensities_buf = []
            elif line == "END IONS":
                if current_id is not None and masses_buf:
                    _flush(current_id, masses_buf, intensities_buf)
                current_id = None
            elif line.startswith("LIBRARY_ID="):
                current_id = line.split("=", 1)[1].strip()
            elif re.match(r"^[\d.]+\s+[\d.]+$", line):
                parts = line.split()
                masses_buf.append(float(parts[0]))
                intensities_buf.append(float(parts[1]))

    logging.info(
        f"Loaded MGF ground truth for {len(ground_truth_map)} molecules from {mgf_path}"
    )
    return ground_truth_map


def make_all_test_splits(labels_path: str) -> pd.DataFrame:
    """Build a synthetic splits DataFrame treating all molecules as test set.

    Works for any metadata file that has a mol_id / spec column.
    """
    df = pd.read_csv(labels_path, sep="\t")
    mol_id_col = "spec" if "spec" in df.columns else "mol_id"
    return pd.DataFrame(
        {"mol_id": df[mol_id_col].astype(str), "split": "test"}
    )


def load_predictions(
    predictions_path: str,
) -> Tuple[Dict, float, float, float]:
    """Load predictions from HDF5 file.

    Returns
    -------
    Tuple[Dict, float, float, float]
        - predictions: Dict mapping mol_id -> {smiles, inchi_key, intensities, mz_bins}
        - min_mz, max_mz, bin_width from file attributes
    """
    predictions = {}

    with h5py.File(predictions_path, "r") as hf:
        min_mz = hf.attrs.get("min_mz", 0)
        max_mz = hf.attrs.get("max_mz", 1000)
        bin_width = hf.attrs.get("bin_width", 1.0)

        for mol_id in tqdm(hf.keys(), desc="Loading predictions"):
            grp = hf[mol_id]
            predictions[mol_id] = {
                "smiles": grp.attrs["smiles"],
                "inchi_key": grp.attrs["inchi_key"],
                "intensities": grp["predicted_intensities"][:],
                "mz_bins": grp["mz_bins"][:],
            }

    logging.info(
        f"Loaded {len(predictions)} predictions from {predictions_path}"
    )
    return predictions, min_mz, max_mz, bin_width


def load_ground_truth(
    spectra_path: str,
    labels_path: str,
    mol_ids: List[str],
    min_mz: float,
    max_mz: float,
    bin_width: float,
) -> Dict:
    """Load and bin ground truth spectra.

    Returns dict mapping smiles -> {mol_id, inchi_key, intensities, mz_bins}
    """
    # Use the helper function from eval_utils
    ground_truth_map, _ = retrieve_ground_truth(
        labels_path=labels_path,
        spectra_path=spectra_path,
        mol_ids=mol_ids,
        min_mz=min_mz,
        max_mz=max_mz,
        bin_width=bin_width,
    )
    return ground_truth_map


def run_similarity_evaluation(
    predictions: Dict,
    ground_truth: Dict,
    labels_df: pd.DataFrame,
    output_dir: Path,
    weighted_cosine_schemes: List[str] = ["nist_gc"],
    composite_schemes: List[str] = ["nist_gc"],
) -> pd.DataFrame:
    """Compute similarity metrics between predictions and ground truth."""
    logging.info("Running similarity evaluation...")

    results = []

    for mol_id, pred_data in tqdm(
        predictions.items(), desc="Computing similarity"
    ):
        smiles = pred_data["smiles"]

        if smiles not in ground_truth:
            continue

        gt_data = ground_truth[smiles]
        pred_spec = pred_data["intensities"]
        true_spec = gt_data["intensities"]
        mz_values = pred_data["mz_bins"]

        if pred_spec.sum() == 0 or true_spec.sum() == 0:
            continue

        if len(pred_spec) != len(true_spec):
            logging.warning(
                f"Shape mismatch for {mol_id}: {len(pred_spec)} vs {len(true_spec)}"
            )
            continue

        row = {
            "mol_id": mol_id,
            "smiles": smiles,
        }

        # Compute the same 8 metrics as eval.py's default config
        metrics_to_compute = [
            "cosine_similarity",
            "entropy_similarity",
            "entropy_distance",
            "spectral_contrast_angle",
            "mean_squared_error",
        ]
        if weighted_cosine_schemes:
            metrics_to_compute.append("weighted_cosine")
        if composite_schemes:
            metrics_to_compute.append("composite_similarity")

        computed_metrics = compute_metrics_for_spectra(
            pred_spec,
            true_spec,
            metrics_to_compute,
            weighted_cosine_schemes,
            composite_schemes,
            mz_values,
        )
        row.update(computed_metrics)

        results.append(row)

    df = pd.DataFrame(results)
    output_path = output_dir / "similarity_results.csv"
    df.to_csv(output_path, index=False)
    logging.info(f"Saved similarity results to {output_path}")

    # Summary
    summary = {}
    for col in df.columns:
        if col not in ["mol_id", "smiles"]:
            summary[f"mean_{col}"] = df[col].mean()
            summary[f"std_{col}"] = df[col].std()

    with open(output_dir / "similarity_summary.txt", "w") as f:
        for k, v in summary.items():
            f.write(f"{k}: {v:.4f}\n")

    logging.info(
        f"Mean cosine similarity: {summary.get('mean_cosine_similarity', 0):.4f}"
    )

    return df


def _build_ns_smi_to_ik14(formula_map: dict) -> dict:
    """Build non-stereo SMILES -> InChIKey-14 lookup from a PubChem formula
    map.

    All stereoisomers of a non-stereo SMILES share the same InChIKey-14 by
    definition, so we just take the first entry in each stereo set.
    """
    ns_smi_to_ik14 = {}
    for isomers in formula_map.values():
        for ns_smi, stereo_set in isomers.items():
            if stereo_set and ns_smi not in ns_smi_to_ik14:
                any_ik = next(iter(stereo_set))[1]
                ns_smi_to_ik14[ns_smi] = any_ik[:14]
    return ns_smi_to_ik14


def _run_retrieval_pubchem_candidates(
    predictions: Dict,
    ground_truth: Dict,
    labels_df: pd.DataFrame,
    splits_df: pd.DataFrame,
    candidates_pickle_path: str,
    formula_map_path: str,
    ranking_metrics: List[str],
    weighted_cosine_schemes: List[str],
    composite_schemes: List[str],
) -> list:
    """Retrieval using prebuilt PubChem isomer candidates keyed by InChIKey-14.

    Loads the candidates pickle (target InChIKey -> {cands: non-stereo SMILES
    array}) and the formula map subset (for ns_smi -> InChIKey-14 lookup). For
    each test target, scores all its PubChem isomer candidates that have a
    prediction, plus the target itself as the correct answer.
    """
    logging.info(f"Loading candidates from {candidates_pickle_path}")
    with open(candidates_pickle_path, "rb") as f:
        cands_dict = pickle.load(f)

    logging.info(f"Loading formula map from {formula_map_path}")
    with open(formula_map_path, "rb") as f:
        formula_map = pickle.load(f)

    ns_smi_to_ik14 = _build_ns_smi_to_ik14(formula_map)
    logging.info(f"Built ns_smi->ik14 map with {len(ns_smi_to_ik14)} entries")

    # Build ik14 -> prediction entry (predictions keyed by mol_id, each has inchi_key attr)
    ik14_to_pred = {}
    for pred in predictions.values():
        ik14 = pred["inchi_key"][:14]
        ik14_to_pred[ik14] = pred

    logging.info(f"Indexed {len(ik14_to_pred)} predictions by InChIKey-14")

    # Get test inchi_keys from splits
    test_mol_ids = set(
        splits_df[splits_df["split"] == "test"]["mol_id"].astype(str)
    )
    mol_id_to_inchikey = labels_df.set_index("mol_id")["inchi_key"].to_dict()
    test_inchikeys = {
        mol_id_to_inchikey[int(mid)]
        for mid in test_mol_ids
        if int(mid) in mol_id_to_inchikey
    }

    all_results = []
    missing_target = 0
    missing_candidates = 0

    for target_ik in tqdm(
        test_inchikeys, desc="Retrieval (PubChem candidates)"
    ):
        if target_ik not in cands_dict:
            missing_target += 1
            continue

        entry = cands_dict[target_ik]
        target_ik14 = target_ik[:14]

        target_pred = ik14_to_pred.get(target_ik14)
        if target_pred is None:
            missing_target += 1
            continue

        target_smiles = target_pred["smiles"]
        if target_smiles not in ground_truth:
            continue

        query_gt = ground_truth[target_smiles]["intensities"]
        mz_values = target_pred["mz_bins"]
        formula = entry.get("formula", "")

        # Score target itself (correct answer)
        if target_pred["intensities"].sum() > 0:
            row = {
                "query_inchikey14": target_ik14,
                "candidate_inchikey14": target_ik14,
                "formula": formula,
                "is_correct": True,
            }
            row.update(
                compute_metrics_for_spectra(
                    target_pred["intensities"],
                    query_gt,
                    ranking_metrics,
                    weighted_cosine_schemes,
                    composite_schemes,
                    mz_values,
                )
            )
            all_results.append(row)

        # Score PubChem isomer candidates
        for ns_smi in entry["cands"]:
            cand_ik14 = ns_smi_to_ik14.get(ns_smi)
            if cand_ik14 is None:
                missing_candidates += 1
                continue

            cand_pred = ik14_to_pred.get(cand_ik14)
            if cand_pred is None:
                missing_candidates += 1
                continue

            if cand_pred["intensities"].sum() == 0:
                continue

            row = {
                "query_inchikey14": target_ik14,
                "candidate_inchikey14": cand_ik14,
                "formula": formula,
                "is_correct": cand_ik14 == target_ik14,
            }
            row.update(
                compute_metrics_for_spectra(
                    cand_pred["intensities"],
                    query_gt,
                    ranking_metrics,
                    weighted_cosine_schemes,
                    composite_schemes,
                    mz_values,
                )
            )
            all_results.append(row)

    logging.info(
        f"Targets missing prediction or candidates pickle: {missing_target}"
    )
    logging.info(
        f"Candidate SMILES with no prediction (not in predictions file): {missing_candidates}"
    )
    return all_results


def _run_retrieval_within_predictions(
    predictions: Dict,
    ground_truth: Dict,
    labels_df: pd.DataFrame,
    splits_df: pd.DataFrame,
    ranking_metrics: List[str],
    weighted_cosine_schemes: List[str],
    composite_schemes: List[str],
) -> list:
    """Retrieval using only molecules present in the predictions file.

    Candidates are all predictions sharing the same molecular formula as the
    query. Only useful if the predictions file covers many molecules per
    formula (e.g. full-dataset inference). For external baselines that only
    predict the test split, candidate counts will be very low — use
    --candidates-pickle instead.
    """
    test_mol_ids = set(
        splits_df[splits_df["split"] == "test"]["mol_id"].astype(str)
    )
    formula_to_mol_ids = (
        labels_df.groupby("formula")["mol_id"].apply(list).to_dict()
    )
    mol_id_to_smiles = labels_df.set_index("mol_id")[
        "standardized_smiles"
    ].to_dict()
    mol_id_to_inchikey = labels_df.set_index("mol_id")["inchi_key"].to_dict()
    mol_id_to_formula = labels_df.set_index("mol_id")["formula"].to_dict()

    all_results = []

    for query_mol_id in tqdm(
        test_mol_ids, desc="Retrieval (within predictions)"
    ):
        if query_mol_id not in predictions:
            continue

        query_smiles = predictions[query_mol_id]["smiles"]
        if query_smiles not in ground_truth:
            continue

        query_gt = ground_truth[query_smiles]["intensities"]
        query_formula = mol_id_to_formula.get(int(query_mol_id))

        if not query_formula or pd.isna(query_formula):
            continue

        candidate_mol_ids = formula_to_mol_ids.get(query_formula, [])

        for cand_mol_id in candidate_mol_ids:
            cand_mol_id_str = str(cand_mol_id)
            if cand_mol_id_str not in predictions:
                continue

            cand_pred = predictions[cand_mol_id_str]["intensities"]
            if cand_pred.sum() == 0:
                continue

            row = {
                "query_mol_id": query_mol_id,
                "candidate_mol_id": cand_mol_id_str,
                "candidate_smiles": mol_id_to_smiles.get(cand_mol_id),
                "candidate_inchikey": mol_id_to_inchikey.get(cand_mol_id),
                "formula": query_formula,
                "is_correct": cand_mol_id_str == query_mol_id,
            }
            row.update(
                compute_metrics_for_spectra(
                    cand_pred,
                    query_gt,
                    ranking_metrics,
                    weighted_cosine_schemes,
                    composite_schemes,
                    predictions[cand_mol_id_str]["mz_bins"],
                )
            )
            all_results.append(row)

    return all_results


def run_retrieval_evaluation(
    predictions: Dict,
    ground_truth: Dict,
    labels_df: pd.DataFrame,
    splits_df: pd.DataFrame,
    output_dir: Path,
    k_max: int = 50,
    ranking_metrics: List[str] = None,
    weighted_cosine_schemes: List[str] = None,
    composite_schemes: List[str] = None,
    candidates_pickle_path: Optional[str] = None,
    formula_map_path: Optional[str] = None,
) -> pd.DataFrame:
    """Run retrieval evaluation.

    If candidates_pickle_path is given, uses prebuilt PubChem isomer candidates
    (from retrieval_create_retrieval_lists.py). Candidates are non-stereo
    SMILES ranked by Tanimoto; the target itself is inserted as the correct
    answer. Lookups are done via InChIKey-14 to avoid SMILES canonicalization
    issues. formula_map_path (pubchem_formula_map_subset.p) is required
    alongside the pickle to map non-stereo SMILES -> InChIKey-14.

    Without candidates_pickle_path, falls back to formula-based retrieval
    within the predictions file only (only useful if predictions cover many
    molecules).
    """
    logging.info("Running retrieval evaluation...")

    if ranking_metrics is None:
        ranking_metrics = [
            "cosine_similarity",
            "entropy_similarity",
            "entropy_distance",
            "spectral_contrast_angle",
            "mean_squared_error",
            "weighted_cosine",
            "composite_similarity",
        ]
    if weighted_cosine_schemes is None:
        weighted_cosine_schemes = ["nist_gc"]
    if composite_schemes is None:
        composite_schemes = ["nist_gc"]

    if candidates_pickle_path is not None:
        if formula_map_path is None:
            raise ValueError(
                "--formula-map is required when using --candidates-pickle"
            )
        all_results = _run_retrieval_pubchem_candidates(
            predictions=predictions,
            ground_truth=ground_truth,
            labels_df=labels_df,
            splits_df=splits_df,
            candidates_pickle_path=candidates_pickle_path,
            formula_map_path=formula_map_path,
            ranking_metrics=ranking_metrics,
            weighted_cosine_schemes=weighted_cosine_schemes,
            composite_schemes=composite_schemes,
        )
    else:
        all_results = _run_retrieval_within_predictions(
            predictions=predictions,
            ground_truth=ground_truth,
            labels_df=labels_df,
            splits_df=splits_df,
            ranking_metrics=ranking_metrics,
            weighted_cosine_schemes=weighted_cosine_schemes,
            composite_schemes=composite_schemes,
        )

    df = pd.DataFrame(all_results)

    if len(df) == 0:
        logging.warning("No retrieval results computed")
        return df

    # Use helper to get similarity column names
    sim_columns = get_similarity_column_names(
        ranking_metrics, weighted_cosine_schemes, composite_schemes
    )

    query_key = (
        "query_inchikey14"
        if "query_inchikey14" in df.columns
        else "query_mol_id"
    )
    for sim_col in sim_columns:
        if sim_col in df.columns:
            df[f"rank_{sim_col}"] = (
                df.groupby(query_key)[sim_col]
                .rank(ascending=False, method="min")
                .astype(int)
            )

    output_path = output_dir / "retrieval_with_formula_results.csv"
    df.to_csv(output_path, index=False)
    logging.info(f"Saved retrieval results to {output_path}")

    with open(output_dir / "retrieval_summary.txt", "w") as f:
        f.write(f"Number of queries: {df[query_key].nunique()}\n")
        f.write(f"Total candidates: {len(df)}\n\n")

        for sim_col in sim_columns:
            rank_col = f"rank_{sim_col}"
            correct_ranks = df[df["is_correct"]][rank_col]

            f.write(f"{sim_col}\n")
            for k in [1, 5, 10, 20, 50]:
                if k <= k_max:
                    top_k = (correct_ranks <= k).mean()
                    f.write(f"  top_{k}_accuracy: {top_k:.4f}\n")

            mrr = (1.0 / correct_ranks).mean()
            f.write(f"  mrr: {mrr:.4f}\n")
            f.write(f"  mean_rank: {correct_ranks.mean():.2f}\n")
            f.write(f"  median_rank: {correct_ranks.median():.2f}\n\n")

            if sim_col == sim_columns[0]:
                logging.info(
                    f"Top-1 ({sim_col}): {(correct_ranks <= 1).mean():.4f}, MRR: {mrr:.4f}"
                )

    return df


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate predictions from baseline models"
    )
    parser.add_argument(
        "--predictions",
        "-p",
        type=str,
        required=True,
        help="Path to predictions HDF5 file",
    )
    parser.add_argument(
        "--ground-truth",
        "-g",
        type=str,
        required=True,
        help="Path to ground truth spectra HDF5 file",
    )
    parser.add_argument(
        "--labels",
        "-l",
        type=str,
        required=True,
        help="Path to metadata TSV file",
    )
    parser.add_argument(
        "--splits",
        "-s",
        type=str,
        default=None,
        help="Path to splits TSV file. Omit when using --all-as-test.",
    )
    parser.add_argument(
        "--output", "-o", type=str, required=True, help="Output directory"
    )
    parser.add_argument(
        "--mode",
        type=str,
        default="all",
        choices=["similarity", "retrieval", "all"],
        help="Evaluation mode",
    )
    parser.add_argument(
        "--k-max", type=int, default=50, help="Maximum k for top-k accuracy"
    )
    parser.add_argument(
        "--candidates-pickle",
        type=str,
        default=None,
        help=(
            "Path to prebuilt PubChem candidates pickle "
            "(e.g. data/NIST2023_GCMS_main/retrieval/cands_pickled_scaffold_50.pkl). "
            "When set, uses PubChem isomers as the candidate pool instead of the "
            "predictions file. Requires --formula-map."
        ),
    )
    parser.add_argument(
        "--formula-map",
        type=str,
        default=None,
        help=(
            "Path to PubChem formula map subset pickle "
            "(e.g. data/NIST2023_GCMS_main/retrieval/pubchem_formula_map_subset.p). "
            "Required when using --candidates-pickle."
        ),
    )
    parser.add_argument(
        "--test-predictions",
        type=str,
        default=None,
        help=(
            "Path to a second predictions HDF5 containing test-split molecules. "
            "When --predictions contains only PubChem candidates, pass the test-split "
            "predictions here so similarity eval and retrieval target lookup both work. "
            "Entries are merged into --predictions (test-predictions takes precedence "
            "on key collision)."
        ),
    )
    parser.add_argument(
        "--all-as-test",
        action="store_true",
        default=False,
        help=(
            "Treat all molecules in --labels as the test set. "
            "Use for datasets without train/val splits. "
            "Mutually exclusive with --splits."
        ),
    )
    args = parser.parse_args()

    if args.all_as_test and args.splits:
        parser.error("--all-as-test and --splits are mutually exclusive")
    if not args.all_as_test and not args.splits:
        parser.error("one of --splits or --all-as-test is required")

    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Setup file logging
    file_handler = logging.FileHandler(output_dir / "evaluation.log")
    file_handler.setFormatter(
        logging.Formatter("%(asctime)s - %(levelname)s - %(message)s")
    )
    logging.getLogger().addHandler(file_handler)

    logging.info(f"Starting evaluation. Output: {output_dir}")

    # Load predictions
    predictions, min_mz, max_mz, bin_width = load_predictions(args.predictions)

    if args.test_predictions:
        logging.info(
            f"Merging test-split predictions from {args.test_predictions}"
        )
        test_preds, *_ = load_predictions(args.test_predictions)
        predictions.update(test_preds)
        logging.info(f"Total predictions after merge: {len(predictions)}")

    # Load labels and splits
    labels_df = pd.read_csv(args.labels, sep="\t")

    if args.all_as_test:
        splits_df = make_all_test_splits(args.labels)
    else:
        splits_df = pd.read_csv(args.splits, sep="\t")

    # Normalise mol_id column so it is always a string "mol_id"
    if "spec" in splits_df.columns and "mol_id" not in splits_df.columns:
        splits_df = splits_df.rename(columns={"spec": "mol_id"})
    if "spec" in labels_df.columns and "mol_id" not in labels_df.columns:
        labels_df = labels_df.rename(columns={"spec": "mol_id"})
    if (
        "smiles" in labels_df.columns
        and "standardized_smiles" not in labels_df.columns
    ):
        labels_df = labels_df.rename(columns={"smiles": "standardized_smiles"})
    if (
        "inchikey" in labels_df.columns
        and "inchi_key" not in labels_df.columns
    ):
        labels_df = labels_df.rename(columns={"inchikey": "inchi_key"})

    # Get test mol_ids
    test_mol_ids = splits_df[splits_df["split"] == "test"]["mol_id"].tolist()

    # Load ground truth — MGF format or HDF5
    gt_path = args.ground_truth
    if gt_path.endswith(".mgf"):
        ground_truth = load_ground_truth_from_mgf(
            gt_path, args.labels, test_mol_ids, min_mz, max_mz, bin_width
        )
    else:
        ground_truth = load_ground_truth(
            gt_path, args.labels, test_mol_ids, min_mz, max_mz, bin_width
        )

    # Run evaluations
    if args.mode in ["similarity", "all"]:
        run_similarity_evaluation(
            predictions, ground_truth, labels_df, output_dir
        )

    if args.mode in ["retrieval", "all"]:
        run_retrieval_evaluation(
            predictions,
            ground_truth,
            labels_df,
            splits_df,
            output_dir,
            k_max=args.k_max,
            candidates_pickle_path=args.candidates_pickle,
            formula_map_path=args.formula_map,
        )

    logging.info("Evaluation complete!")


if __name__ == "__main__":
    main()
